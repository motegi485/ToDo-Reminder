-- サブタスク（1 タスクの中の折りたたみチェックリスト）を親行の 1 列に持たせるための列。
--
-- 子を独立行にしない理由: 子 1 件を 1 行にすると、tasks を読むすべての箇所
-- （sort.ts / useProjects.ts / ProjectGroup.tsx / reports.ts / offlineNotify.ts）に
-- 「子を除外する」フィルタが要る。1 箇所でも抜けると一覧に子が単独行として並び、
-- プロジェクトの未完了件数も狂う（0007 でメモを足したときに 3 箇所で踏んだ罠）。
-- サブタスクは親と一緒に編集されるひとかたまりで、独立に検索・通知・並べ替えの
-- 対象にならないため、行を増やす価値が小さい。
--
-- 代償は LWW の粒度が親行単位になること。2 端末が同時に別々の子をチェックすると、
-- 後勝ちで片方のチェックが消える。「2 台を日常的に使うが同じタスクを同時には触らない」
-- という利用実態を確認したうえで受け入れている（docs/data-model.md）。
--
-- 形式は recurrence_rule と同じ JSON 文字列。
--   '[{"id":"<uuid>","title":"住所変更","done":true}, ...]'
-- サーバーはこの中身を一切解釈せず、配列であることと長さ（SUBTASKS_MAX_BYTES）だけを
-- 見て素通しで保存・返却する。
--
-- CHECK 制約は付けない: 0005_add_color.sql / 0007_add_memo_columns.sql と同じ理由で、
-- 値の集合が将来増えるものにサーバー側の制約を持たせると、クライアントを更新した瞬間に
-- 同期が CHECK constraint failed で全滅する。
--
-- 既存行はすべて NULL で始まる（= サブタスクなし）。

ALTER TABLE tasks ADD COLUMN subtasks TEXT;
